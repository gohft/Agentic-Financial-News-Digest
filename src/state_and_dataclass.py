@dataclass
class EvaluationResult:
    """
    Represents the output after evaluating one generated summary.

    Attributes:
        feedback: Metric scores and comments after evaluating the summary as Feedback object.
        messages: System and input prompt for the LLM to do the evaluation.
    """

    feedback: Feedback
    messages: list[AnyMessage]


class SharedState(TypedDict):
    """
    Shared state that is accessible across all nodes in the graph.
    All variables are rewritten by nodes since previous states like
    past summaries/feedback does not affect each node.

    Only messages is not rewritten but appended to track LLM calls.

    Attributes:
        messages: List of system and user prompts of type AnyMessage used in all LLM in graph.
        gathered_data: List of Articles extracted from the RSS feed url.
        past_summaries:  List of past ArticleSummary that has similar content as any of the Articles in gathered_data.
        current_summary: List of ArticleSummary of importance news generated by the generator LLM from gathered_data.
        critic_feedback: List of Feedback, one for each ArticleSummary in current_summary generated from the critic LLM.
        approved: Approval status of the generated summaries in boolean type.
        critic_count: Number of times feedback was given for the generated summaries.
    """

    # store all messages from LLM calls
    # reducer function `add_messages` to append message (without duplicates) instead of rewriting
    messages: Annotated[list[AnyMessage], add_messages]
    gathered_data: list[Article]
    past_summaries: list[ArticleSummary]
    current_summary: list[ArticleSummary]
    critic_feedback: list[Feedback]
    approved: bool
    critic_count: int  # track to prevent infinite loop
